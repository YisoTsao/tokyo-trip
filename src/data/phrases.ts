// Travel conversations for every situation on the itinerary, in Japanese / 中文 / English.
// Japanese text marks readings inline as {漢字|かな}; the page turns them into <ruby> furigana
// and reads the kana aloud, so every kanji word in `ja` should carry a reading.
// Staff replies are typical examples: real answers (platforms, prices, times) can differ on the day.
import type { IconName } from "../illustrations/journal/icons";

export interface Line {
  /** true = the traveller (我), false = the person you are talking to */
  me: boolean;
  ja: string;
  zh: string;
  en: string;
}

export interface Scene {
  id: string;
  title: string;
  /** where it happens, shown under the title */
  where: string;
  /** label for the other speaker, e.g. 站員 */
  them: string;
  icon: IconName;
  lines: Line[];
  tip?: string;
  /** words you are likely to hear back: [ja, zh] */
  hear?: [string, string][];
}

export interface PhraseGroup {
  id: string;
  /** chip label */
  chip: string;
  kicker: string;
  title: string;
  sub?: string;
  scenes: Scene[];
}

